import { useEffect, useState } from 'react';
import type { RenderScale, ImageExportResult } from '../utils/imageExport';
import { isTauri } from '../utils/tauri';
import { useFamilyStore } from '../store/familyStore';
import { isAutoGeneratedPerson } from '../utils';

// 以苒纪 — 另存为弹窗（左选格式，右看详情）
//
// 左侧为三个导出类别：YRJ 档案 / 图片（JPG·PNG）/ HTML 网页；
// 右侧为对应详情面板：格式子选项（图片类）、渲染倍率、默认文件名预览与保存按钮。

export type ExportCategory = 'yrj' | 'image' | 'html' | 'json';
export type ExportFormat = 'yrj' | 'jpg' | 'png' | 'html';

export type NotifyFn = (text: string, type: 'success' | 'error' | 'info') => void;

interface SaveAsDialogProps {
  open: boolean;
  familyName: string;
  onClose: () => void;
  /** YRJ 档案导出（复用 store 的 saveProjectAs），返回是否成功 */
  onExportYrj: () => Promise<boolean>;
  /** 图片导出（MainLayout 负责确保画布就绪），返回保存结果 */
  onExportImage: (format: 'jpg' | 'png', renderScale: RenderScale, options?: { includePlaceholders?: boolean }) => Promise<ImageExportResult>;
  /** HTML 导出，返回保存结果 */
  onExportHtml: (options?: { includePlaceholders?: boolean }) => Promise<'saved' | 'cancelled'>;
  /** 结果通知（toast 由父组件渲染） */
  notify: NotifyFn;
}

// 导入导出JSON数据的功能为开发时调整前端时专用，请勿将此功能显示到桌面版中。
const CATEGORY_OPTIONS: Array<{
  id: ExportCategory;
  icon: string;
  title: string;
  brief: string;
}> = [
  { id: 'yrj', icon: '🗂️', title: 'YRJ 档案', brief: '完整档案可再编辑' },
  { id: 'image', icon: '🖼️', title: '图片', brief: 'PNG · JPG' },
  { id: 'html', icon: '🌐', title: 'HTML 网页', brief: '可缩放 · 切换主视角' },
  ...(!isTauri()
    ? [
        {
          id: 'json' as const,
          icon: '📄',
          title: 'JSON 数据',
          brief: '纯数据 · 网页调试专用',
        },
      ]
    : []),
];

const CATEGORY_DETAILS: Record<
  ExportCategory,
  { title: string; desc: string }
> = {
  yrj: {
    title: 'YRJ 档案',
    desc: '打包全部人员信息与照片为单个档案文件，可再次打开编辑，适合长期保存与迁移。档案设置了密码时会自动加密。',
  },
  image: {
    title: '图片',
    desc: '将整棵家谱树渲染为一张高清大图，适合发朋友圈、微信群或插入文档。',
  },
  html: {
    title: 'HTML 网页',
    desc: '单文件网页，双击即可在浏览器打开。只读不可编辑：可滚轮缩放、拖拽平移、悬浮卡片查看「我是他 / 他是我」双向称谓，还能在右上角切换主视角，适合发给亲友各自查看。',
  },
  json: {
    title: 'JSON 数据',
    desc: '导出当前工程的完整 project.json 数据文件，仅包含文字与结构数据。专供网页模式下测试与再次导入使用。',
  },
};

const IMAGE_FORMAT_INFO: Record<'png' | 'jpg', { label: string; desc: string }> = {
  png: { label: 'PNG', desc: '无损画质，文字与线条更锐利' },
  jpg: { label: 'JPG', desc: '智能压缩，体积小巧便于分享' },
};

const SCALE_OPTIONS: RenderScale[] = [1, 2, 3, 4];

export default function SaveAsDialog({
  open,
  familyName,
  onClose,
  onExportYrj,
  onExportImage,
  onExportHtml,
  notify,
}: SaveAsDialogProps) {
  const [category, setCategory] = useState<ExportCategory>(() => isTauri() ? 'yrj' : 'image');
  const [imageFormat, setImageFormat] = useState<'png' | 'jpg'>('png');
  const [renderScale, setRenderScale] = useState<RenderScale>(2);
  const [includePlaceholders, setIncludePlaceholders] = useState(false);
  const [isExporting, setIsExporting] = useState(false);

  const project = useFamilyStore((state) => state.project);
  const hasPlaceholders = Object.values(project?.persons || {}).some(isAutoGeneratedPerson);

  // 每次打开时重置选择状态
  useEffect(() => {
    if (open) {
      setCategory(isTauri() ? 'yrj' : 'image');
      setImageFormat('png');
      setRenderScale(2);
      setIncludePlaceholders(false);
      setIsExporting(false);
    }
  }, [open]);

  if (!open) return null;

  const detail = CATEGORY_DETAILS[category];
  const isImage = category === 'image';

  const confirmLabel =
    category === 'yrj'
      ? '保存档案'
      : isImage
        ? `保存为 ${IMAGE_FORMAT_INFO[imageFormat].label}`
        : category === 'html'
          ? '保存网页'
          : '导出 JSON 数据';

  const handleConfirm = async () => {
    if (isExporting) return;
    setIsExporting(true);

    try {
      if (category === 'yrj') {
        const ok = await onExportYrj();
        if (!ok) return;
        notify('YRJ 档案已成功导出！', 'success');
        onClose();
      } else if (isImage) {
        const result = await onExportImage(imageFormat, renderScale, { includePlaceholders });
        if (result.status === 'cancelled') return;
        if (result.warning) {
          notify(result.warning, 'info');
        }
        notify(
          `家谱图 ${imageFormat.toUpperCase()} 已成功导出！${result.warning ? '（倍率已自动调整）' : ''}`,
          'success'
        );
        onClose();
      } else if (category === 'html') {
        const result = await onExportHtml({ includePlaceholders });
        if (result === 'cancelled') return;
        notify('家谱图 HTML 网页已成功导出！', 'success');
        onClose();
      } else if (category === 'json') {
        // 导入导出JSON数据的功能为开发时调整前端时专用，请勿将此功能显示到桌面版中。
        const project = useFamilyStore.getState().project;
        if (!project) return;
        const jsonStr = JSON.stringify(project, null, 2);
        const blob = new Blob([jsonStr], { type: 'application/json' });
        const url = URL.createObjectURL(blob);
        const a = document.createElement('a');
        a.href = url;
        a.download = `${familyName || '以苒纪家谱'}_工程数据.json`;
        document.body.appendChild(a);
        a.click();
        document.body.removeChild(a);
        URL.revokeObjectURL(url);
        notify('工程 JSON 数据已成功导出下载！', 'success');
        onClose();
      }
    } catch (err) {
      console.error('导出失败:', err);
      notify(`导出失败：${(err as Error)?.message || '未知错误'}`, 'error');
    } finally {
      setIsExporting(false);
    }
  };

  return (
    <div className="saveas-overlay" onClick={() => !isExporting && onClose()}>
      <div className="saveas-dialog" onClick={(e) => e.stopPropagation()}>
        <div className="saveas-header">
          <div className="saveas-title-group" style={{ display: 'flex', alignItems: 'baseline', gap: '10px', minWidth: 0 }}>
            <div className="saveas-title">另存为</div>
            {!isTauri() && (
              <span className="saveas-header-web-hint" style={{ fontSize: '12px', color: 'var(--color-text-tertiary)', fontWeight: 'normal' }}>
                浏览器模式：点击保存后会下载到系统的「下载」文件夹
              </span>
            )}
          </div>
          <div className="saveas-subtitle">{familyName}</div>
        </div>
        <div className="saveas-body">
          {/* 左侧：类别选择 */}
          <nav className="saveas-category-list">
            {CATEGORY_OPTIONS.map((opt) => {
              const isWebYrj = opt.id === 'yrj' && !isTauri();
              return (
                <button
                  key={opt.id}
                  type="button"
                  className={`saveas-category-item ${category === opt.id ? 'selected' : ''}`}
                  onClick={() => setCategory(opt.id)}
                  disabled={isExporting}
                  style={isWebYrj && category !== opt.id ? { opacity: 0.6 } : undefined}
                  title={isWebYrj ? '仅桌面版客户端支持导出 YRJ 档案' : undefined}
                >
                  <span className="saveas-category-icon">{opt.icon}</span>
                  <span className="saveas-category-info">
                    <span className="saveas-category-title">{opt.title}</span>
                    <span className="saveas-category-brief">
                      {isWebYrj ? '仅桌面版客户端支持' : opt.brief}
                    </span>
                  </span>
                </button>
              );
            })}
          </nav>

          {/* 右侧：详情面板 */}
          <div className="saveas-detail">
            <div className="saveas-detail-header">
              <div className="saveas-detail-title">{detail.title}</div>
              <div className="saveas-detail-desc">{detail.desc}</div>
              {!isTauri() && category === 'yrj' && (
                <div className="saveas-web-hint" style={{ color: 'var(--color-warning, #d97706)', marginTop: '8px' }}>
                  ⚠️ 网页版受浏览器沙箱限制，无法打包导出包含本地磁盘媒体的 YRJ 档案。如需完整归档与媒体管理，请使用桌面版客户端，或导出「JSON 数据」。
                </div>
              )}
            </div>

            {/* 若工程存在占位人员，提供是否导出的复选框 */}
            {hasPlaceholders && (isImage || category === 'html') && (
              <div className="saveas-placeholder-row">
                <label className="saveas-placeholder-label">
                  <input
                    type="checkbox"
                    checked={includePlaceholders}
                    onChange={(e) => setIncludePlaceholders(e.target.checked)}
                    disabled={isExporting}
                  />
                  <span>包含系统占位成员（用于补全手足关系的虚拟父母）</span>
                </label>
              </div>
            )}

            {isImage && (
              <>
                {/* 图片格式子选项：JPG / PNG */}
                <div className="saveas-image-formats">
                  {(['png', 'jpg'] as const).map((f) => (
                    <button
                      key={f}
                      type="button"
                      className={`saveas-image-format ${imageFormat === f ? 'selected' : ''}`}
                      onClick={() => setImageFormat(f)}
                      disabled={isExporting}
                    >
                      <span className="saveas-image-format-label">
                        {IMAGE_FORMAT_INFO[f].label}
                      </span>
                      <span className="saveas-image-format-desc">
                        {IMAGE_FORMAT_INFO[f].desc}
                      </span>
                    </button>
                  ))}
                </div>

                {/* 渲染倍率 */}
                <div className="saveas-scale-row">
                  <span className="saveas-scale-label">渲染倍率</span>
                  <div className="saveas-scale-options">
                    {SCALE_OPTIONS.map((s) => (
                      <button
                        key={s}
                        type="button"
                        className={`saveas-scale-option ${renderScale === s ? 'selected' : ''}`}
                        onClick={() => setRenderScale(s)}
                        disabled={isExporting}
                      >
                        {s}x
                        {s === 2 && <em className="saveas-scale-tag">推荐</em>}
                      </button>
                    ))}
                  </div>
                  <span className="saveas-scale-hint">倍率越高越清晰，文件也越大</span>
                </div>
              </>
            )}

            {/* 保存按钮 */}
            <div className="saveas-footer">
              <button
                type="button"
                className="btn btn-secondary btn-sm"
                onClick={onClose}
                disabled={isExporting}
              >
                取消
              </button>
              <button
                type="button"
                className="btn btn-primary btn-sm saveas-confirm-btn"
                onClick={handleConfirm}
                disabled={isExporting || (category === 'yrj' && !isTauri())}
                title={category === 'yrj' && !isTauri() ? '网页版受浏览器沙箱限制，不支持导出 YRJ 档案，请使用桌面版客户端' : undefined}
              >
                {isExporting
                  ? '⏳ 导出中…'
                  : category === 'yrj' && !isTauri()
                    ? '网页版不可用'
                    : confirmLabel}
              </button>
            </div>
          </div>
        </div>
      </div>
    </div>
  );
}
