// 以苒纪 — 核心类型定义

// ==================== 数据版本 ====================

/**
 * 家谱档案格式版本（schema version，不是软件版本）。
 *
 * 这是软件内置的常量，用户不可设定：新建家谱一律写入此版本
 * （见 createDefaultMeta），旧档案打开时由 migrateProjectData 升级到此版本。
 * 设置页「基本信息」里展示给用户看的就是它。
 *
 * 版本号管的是「档案格式」这份契约，包含三件事，任一发生不兼容变更都必须升位：
 *   1. project.yrp 内 JSON 的字段结构（增删字段、改字段含义）；
 *   2. 工作区 media 目录布局（见 utils/mediaPaths.ts）；
 *   3. 关系数据的合法性强约束（见 utils/relationRules.ts）。
 *
 * 升位规则：不兼容变更升次版本号（2.1.0 → 2.2.0）；只加可选字段、不影响旧档读取升修订号。
 *
 * 变更履历：
 *   2.1.0 关系数据强约束（自指 / 成环 / 角色互斥 / 年龄倒挂）与养父母分组结构；
 *   2.2.0 工作区媒体按类型分目录：media/photo、media/avatar/{circle,rect}、media/video、media/audio。
 */
export const CURRENT_DATA_VERSION = '2.2.0';

// ==================== 基础类型 ====================

export type Gender = 'male' | 'female';

/** 时间精度：只记录日期 or 精确到时分秒 */
export type TimePrecision = 'date' | 'time';

/** 农历日期 */
export interface LunarDate {
  year: number;
  month: number;       // 绝对月份（1-12），不区分闰
  day: number;
  isLeap: boolean;     // 是否闰月
  monthChinese?: string; // 库返回的中文月名，如"三"或"闰三"
  dayChinese?: string;   // 库返回的中文日名，如"廿三"
}

/** 照片 */
export interface Photo {
  id: string;
  path: string;      // 资源路径（相对路径或 blob URL）
  date?: string;      // 拍摄日期 YYYY-MM-DD
  caption?: string;   // 描述
  /** 标记这张照片是哪种头像的「头像原图」；被头像引用期间不允许删除 */
  avatarOriginalFor?: Array<'circle' | 'rect'>;
}

/** 音频文件 */
export interface AudioFile {
  id: string;
  path: string;
  date?: string;
  caption?: string;
}

/** 视频文件 */
export interface VideoFile {
  id: string;
  path: string;
  date?: string;
  caption?: string;
  thumbnail?: string;     // 视频封面缩略图（base64 或路径）
  width?: number;         // 视频原始宽度
  height?: number;        // 视频原始高度
  duration?: number;      // 视频时长（秒）
}

// ==================== 关系类型 ====================

/** 配偶关系类型 */
export type SpouseRelationType = 'married' | 'divorced' | 'deceased';

/** 配偶婚次类型 */
export type SpouseOrderType = 'first' | 'second' | 'third' | 'other';

/** 子女关系类型 */
export type ChildRelationType = 'biological' | 'adopted' | 'step';

/** 配偶关系 */
export interface SpouseRelation {
  id: string;             // 对方的 person id
  type: SpouseRelationType;
  orderType?: SpouseOrderType; // 婚次：first(原配) | second(二婚) | third(三婚) | other(配偶/未指定)
  marriageDate?: string;
  divorceDate?: string;
}

/** 子女关系 */
export interface ChildRelation {
  id: string;             // 对方的 person id
  type: ChildRelationType;
}

/**
 * 养父母分组：一组养父母 = 养父 + 养母，任一方可为空（单亲收养）。
 * 两位养父 / 两位养母通过多组实现，性别不限。
 */
export interface AdoptiveParentGroup {
  id: string;
  fatherId?: string;
  motherId?: string;
}

/** 人员关系集合 */
export interface Relations {
  father?: string;
  mother?: string;
  adoptiveFather?: string;       // 单值（旧版兼容）
  adoptiveMother?: string;       // 单值（旧版兼容）
  adoptiveFathers?: string[];    // 多养父（旧版兼容，新档案不再写入）
  adoptiveMothers?: string[];    // 多养母（旧版兼容，新档案不再写入）
  adoptiveParents?: AdoptiveParentGroup[];  // 养父母分组（新版，存在即权威）
  stepFather?: string;
  stepMother?: string;
  spouses: SpouseRelation[];
  children: ChildRelation[];
}

// ==================== 人员 ====================

export interface Person {
  id: string;
  surname: string;            // 姓
  givenName: string;          // 名
  gender: Gender;

  // 出生日期
  birthDateSolar?: string;    // ISO datetime string, e.g. "1990-01-15T08:30:00"
  birthTimePrecision: TimePrecision;
  birthDateLunar?: LunarDate;

  // 逝世日期
  deathDateSolar?: string;
  deathTimePrecision: TimePrecision;
  deathDateLunar?: LunarDate;

  isAlive: boolean;
  birthPlace?: string;
  residencePlace?: string;     // 居住地
  birthPlaceMode?: 'unknown' | 'regions' | 'custom';
  residencePlaceMode?: 'unknown' | 'regions' | 'custom';
  bio?: string;               // 个人简介

  // 头像
  avatar?: string;            // 头像路径（圆形裁剪，用于家谱树/列表展示）
  avatarRect?: string;        // 头像原始图片路径（矩形/正方形，用于个人信息页左侧展示）
  avatarPhotoDate?: string;   // 头像拍摄日期 YYYY-MM-DD
  avatarRectPhotoDate?: string; // 形象照拍摄日期 YYYY-MM-DD

  // 媒体文件
  photos: Photo[];
  audioFiles: AudioFile[];
  videoFiles: VideoFile[];

  // 关系
  relations: Relations;

  // 是否为默认视角
  isDefaultPerspective: boolean;

  // 是否为系统自动生成的占位节点（如关联手足时自动生成未详名字的父母节点）
  isAutoGenerated?: boolean;

  createdAt: string;
  updatedAt: string;
}

// ==================== 家谱元数据 ====================

export interface FamilyMeta {
  version: string;
  familyName: string;         // e.g. "莫氏-以苒纪"
  surname: string;            // e.g. "莫"
  hasPassword: boolean;
  passwordHash?: string;      // 密码安全哈希（加盐）
  createdAt: string;
  updatedAt: string;
  defaultPerspectiveId?: string;
  description?: string;
  /**
   * 同辈手写排序：personId → 在其兄弟姐妹组中的位次（0 = 最年长）。
   * 出生日期未知的人默认排在已知者右侧，可用「同辈排序」面板手动指定长幼，
   * 排序结果同时决定称谓（兄/弟、姐/妹、伯/叔 等）。
   */
  siblingOrder?: Record<string, number>;
  /**
   * 云同步标识：每个家谱一个稳定 ID，云端用它区分子目录。
   * 不随导入/另存改变，因此两台电脑能定位到同一份云端档案。
   */
  syncKey?: string;
}

// ==================== 应用状态 ====================

export interface FamilyProject {
  meta: FamilyMeta;
  persons: Record<string, Person>;
  customLayout?: Record<string, { x: number; y: number }>;
  /** 经典模式（主脉居中、长幼阶梯错落）下的自定义节点坐标快照 */
  customLayoutClassic?: Record<string, { x: number; y: number }>;
  /** 同辈齐平模式（代际齐平、从左到右）下的自定义节点坐标快照 */
  customLayoutAligned?: Record<string, { x: number; y: number }>;
  /**
   * 自定义布局快照是否已包含侧栏卡片（养/继父母、多配偶等）的坐标。
   * 旧版快照没有这个标记，加载时会重新摆位侧栏卡，避免把历史遗留的
   * 错误坐标当成用户意图；用户拖动或手动输入坐标后快照带上标记，此后原样恢复。
   */
  sideCardsPinned?: boolean;
}

/** 最近打开的项目记录 */
export interface RecentProject {
  familyName: string;
  surname: string;
  lastOpenedAt: string;
  filePath?: string;          // 将来用于 Tauri 文件路径
  projectId: string;          // localStorage key
}

// ==================== 创建人员的默认值工厂 ====================

export function createDefaultPerson(surname: string): Omit<Person, 'id' | 'createdAt' | 'updatedAt'> {
  return {
    surname,
    givenName: '',
    gender: 'male',
    birthTimePrecision: 'date',
    deathTimePrecision: 'date',
    isAlive: true,
    photos: [],
    audioFiles: [],
    videoFiles: [],
    relations: {
      spouses: [],
      children: [],
    },
    isDefaultPerspective: false,
  };
}

export function createDefaultMeta(surname: string): Omit<FamilyMeta, 'createdAt' | 'updatedAt'> {
  return {
    version: CURRENT_DATA_VERSION,
    familyName: `${surname}氏-以苒纪`,
    surname,
    hasPassword: false,
  };
}

// ==================== 养父母兼容工具 ====================

let adoptiveGroupSeq = 0;

/** 生成养父母组的稳定 id（用于增删与 React key） */
export function createAdoptiveGroupId(): string {
  if (typeof crypto !== 'undefined' && typeof crypto.randomUUID === 'function') {
    return crypto.randomUUID();
  }
  adoptiveGroupSeq += 1;
  return `ap-${Date.now()}-${adoptiveGroupSeq}`;
}

/**
 * 读取养父母分组。
 * 新档案直接使用 adoptiveParents（即使为空数组也视为权威）；
 * 旧档案没有该字段，按索引把 adoptiveFathers / adoptiveMothers 配成组
 * ——旧界面是左右两列并排填写，用户通常是按行对应的。
 */
export function getAdoptiveGroups(relations: Relations): AdoptiveParentGroup[] {
  if (relations.adoptiveParents) return relations.adoptiveParents;
  const fathers = relations.adoptiveFathers?.length
    ? relations.adoptiveFathers
    : relations.adoptiveFather
      ? [relations.adoptiveFather]
      : [];
  const mothers = relations.adoptiveMothers?.length
    ? relations.adoptiveMothers
    : relations.adoptiveMother
      ? [relations.adoptiveMother]
      : [];
  const count = Math.max(fathers.length, mothers.length);
  const groups: AdoptiveParentGroup[] = [];
  for (let i = 0; i < count; i += 1) {
    groups.push({
      id: `legacy-${i}`,
      fatherId: fathers[i] || undefined,
      motherId: mothers[i] || undefined,
    });
  }
  return groups;
}

/** 获取所有养父ID（新结构 + 旧版单值/数组兼容） */
export function getAdoptiveFathers(relations: Relations): string[] {
  return getAdoptiveGroups(relations)
    .map((group) => group.fatherId)
    .filter((id): id is string => Boolean(id));
}

/** 获取所有养母ID（新结构 + 旧版单值/数组兼容） */
export function getAdoptiveMothers(relations: Relations): string[] {
  return getAdoptiveGroups(relations)
    .map((group) => group.motherId)
    .filter((id): id is string => Boolean(id));
}

/**
 * 从养父母分组中移除某人（删人 / 断关系时用）。
 * 组内两方都空则整组消失。
 */
export function removePersonFromAdoptiveGroups(
  groups: AdoptiveParentGroup[] | undefined,
  personId: string
): AdoptiveParentGroup[] | undefined {
  if (!Array.isArray(groups)) return groups;
  return groups
    .map((group) => ({
      ...group,
      fatherId: group.fatherId === personId ? undefined : group.fatherId,
      motherId: group.motherId === personId ? undefined : group.motherId,
    }))
    .filter((group) => Boolean(group.fatherId || group.motherId));
}
