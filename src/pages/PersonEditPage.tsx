  const buildSolarMonthOptions = (year: number, month: number): number[] => {
    const maxMonth = year === dateLimit.year ? dateLimit.month : 12;
    const months = Array.from({ length: maxMonth }, (_, i) => i + 1);
    if (month > maxMonth) months.push(month);
    return months;
  };

