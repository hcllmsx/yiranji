          id: genMotherId,
          surname: surname || project.meta.surname || '未设置',
          givenName: '（母亲）',
          gender: 'female',
          birthTimePrecision: 'date',
          deathTimePrecision: 'date',
          isAlive: true,
          isAutoGenerated: true,
          photos: [],
          audioFiles: [],
          videoFiles: [],
          relations: { spouses: [{ id: genFatherId, type: 'married' }], children: [] },
          isDefaultPerspective: false,
          createdAt: now,
          updatedAt: now,
