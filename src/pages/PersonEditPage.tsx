          id: genFatherId,
          surname: surname || project.meta.surname || '未设置',
          givenName: '（父亲）',
          gender: 'male',
          birthTimePrecision: 'date',
          deathTimePrecision: 'date',
          isAlive: true,
          isAutoGenerated: true,
          photos: [],
          audioFiles: [],
          videoFiles: [],
          relations: { spouses: [{ id: genMotherId, type: 'married' }], children: [] },
          isDefaultPerspective: false,
          createdAt: now,
          updatedAt: now,
