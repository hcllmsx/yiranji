  // 公历年份选项：上限为上限年份（随系统时间自动前移），并包容历史数据里超范围的年份
  const solarYearOptions = useMemo(
    () => buildYearOptions(dateLimit.year, Math.max(sBirthYear, sDeathYear)),
    [dateLimit.year, sBirthYear, sDeathYear]
  );

