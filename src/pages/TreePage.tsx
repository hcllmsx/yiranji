interface PersonNodeData {
  person: Person;
  isPerspective: boolean;
  /** 侧栏卡片类型：attached = 关系附属（养/继父母、第二配偶等），isolated = 真孤立 */
  sideKind?: 'attached' | 'isolated';
  showCoordinates?: boolean;
  onHoverStart?: (personId: string) => void;
  onHoverEnd?: () => void;
  /** 手动输入坐标后提交：写入自定义布局快照，保证切换视图/重开后仍保留 */
  onCoordinateCommit?: (personId: string, x: number, y: number) => void;
  isPlaceholderHidden?: boolean;
  placeholderStatus?: 'active' | 'fading' | 'hidden';
  isPathHighlight?: boolean;
  isSpouseSemi?: boolean;
  isDimmed?: boolean;
  pulseDelay?: number;
}

function PersonNode({ data }: { data: PersonNodeData }) {
  const {
    person,
    isPerspective,
    sideKind,
    showCoordinates,
    onHoverStart,
    onHoverEnd,
    onCoordinateCommit,
    isPathHighlight,
    isSpouseSemi,
    isDimmed,
    pulseDelay,
  } = data;
  const navigate = useNavigate();
  const project = useFamilyStore((state) => state.project);
  const isAnonymized = useFamilyStore((state) => state.isAnonymized);
  const anonymizedNames = useFamilyStore((state) => state.anonymizedNames);
  const perspectiveId = project?.meta.defaultPerspectiveId;
  const personsMap = project?.persons || {};
  const relationText = getRelationshipText(
    person.id,
    perspectiveId,
    personsMap,
    project?.meta.siblingOrder
  );
  // 反向称谓：我对该人而言是什么（用于“我是他 X”）
  const isPerspectiveSelf = !!perspectiveId && person.id === perspectiveId;
  const reverseRelationText =
    !isPerspectiveSelf && perspectiveId
      ? getRelationshipText(perspectiveId, person.id, personsMap, project?.meta.siblingOrder)
      : '';
  const isGenericReciprocalRelation =
    !isPerspectiveSelf && relationText === '家族成员' && reverseRelationText === '家族成员';
  const selfPronoun = person.gender === 'male' ? '他' : '她';

  // 使用 useReactFlow 更新自身节点坐标
  const { setNodes } = useReactFlow();

  // 使用 useNodes 动态获取自身的实时坐标，在拖拽时实现 real-time 刷新显示
  const nodes = useNodes();
  const selfNode = nodes.find(n => n.id === person.id);
  const posX = selfNode?.position?.x ?? 0;
  const posY = selfNode?.position?.y ?? 0;

  const [isEditing, setIsEditing] = useState(false);
  const [editX, setEditX] = useState('');
  const [editY, setEditY] = useState('');
  // 头像大图查看

  // 节点被拖拽时，若非编辑态，则自动更新输入框中的预设值
  useEffect(() => {
    if (!isEditing) {
      setEditX(Math.round(posX).toString());
      setEditY(Math.round(posY).toString());
    }
  }, [posX, posY, isEditing]);

  const handleUpdateCoordinates = (newX: number, newY: number) => {
    setNodes((prevNodes) =>
      prevNodes.map((n) => {
        if (n.id === person.id) {
          return {
            ...n,
            position: { x: newX, y: newY },
          };
        }
        return n;
      })
    );
  };

  const handleSave = (e?: React.MouseEvent | React.KeyboardEvent) => {
    if (e) {
      e.stopPropagation();
      e.preventDefault();
    }
    const newX = parseFloat(editX);
    const newY = parseFloat(editY);
    if (!isNaN(newX) && !isNaN(newY)) {
      // 优先交给父级提交（同时写入自定义布局快照）；没有回调时只更新画布
      if (onCoordinateCommit) {
        onCoordinateCommit(person.id, newX, newY);
      } else {
        handleUpdateCoordinates(newX, newY);
      }
    }
    setIsEditing(false);
  };

  const handleCancel = (e?: React.MouseEvent) => {
    if (e) {
      e.stopPropagation();
      e.preventDefault();
    }
    setEditX(Math.round(posX).toString());
    setEditY(Math.round(posY).toString());
    setIsEditing(false);
  };

  const handleKeyDown = (e: React.KeyboardEvent) => {
    e.stopPropagation();
    if (e.key === 'Enter') {
      handleSave(e);
    } else if (e.key === 'Escape') {
      handleCancel(e as any);
    }
  };

  const fullName = isAnonymized
    ? (anonymizedNames[person.id] || '未知')
    : (getFullName(person.surname, person.givenName) || '未命名');

  const genderText = person.gender === 'male' ? '男' : '女';
  let subtitle = genderText;

  // isAlive 未显式设置时默认视为在世，避免误入已故分支显示 "2025—"
  if (person.isAlive !== false) {
    const age = person.birthDateSolar ? formatAge(person.birthDateSolar) : '';
    if (age) {
      subtitle += ` · ${age}`;
    }
  } else {
    const lifeSpan = getLifeSpan(person.birthDateSolar, person.deathDateSolar, person.isAlive);
    if (lifeSpan) {
      subtitle += ` · ${lifeSpan}`;
    }
  }

  const isPlaceholder = isAutoGeneratedPerson(person);
  const placeholderStatus = data.placeholderStatus ?? (isPlaceholder ? (data.isPlaceholderHidden ? 'hidden' : 'active') : undefined);
  const statusClass = placeholderStatus ? ` placeholder-${placeholderStatus}` : '';

  return (
    <div
      className={`tree-person-node ${person.gender} ${isPerspective ? 'perspective' : ''}${sideKind ? ` side-${sideKind}` : ''}${isPlaceholder ? ' is-placeholder' : ''}${statusClass}${isPathHighlight ? ' is-path-highlight' : ''}${isSpouseSemi ? ' is-spouse-semi' : ''}${isDimmed ? ' is-dimmed' : ''}`}
      style={pulseDelay !== undefined ? ({ '--pulse-delay': `${pulseDelay}s` } as React.CSSProperties) : undefined}
      onDoubleClick={() => navigate(`/person/${person.id}`)}
      onMouseEnter={() => onHoverStart?.(person.id)}
      onMouseLeave={() => onHoverEnd?.()}
    >
      <Handle type="target" position={Position.Top} id="top" style={{ opacity: 0 }} />

      {isPerspective && (
        <div className="tree-node-perspective-tag">★</div>
      )}

      {isPlaceholder && (
        <div
          className="tree-node-placeholder-tag"
          style={isPerspective ? { right: 'auto', left: '-8px' } : undefined}
          title="系统为连接手足关系自动生成的占位节点（可双击进入编辑完善信息）"
        >
          占位
        </div>
      )}

      {/* 悬停关系气泡：我对他而言是什么 + 他对我而言是什么 */}
      {relationText && (
        <div className="tree-node-relation-badge">
          {isPerspectiveSelf ? (
            <span className="tree-node-relation-line">★ 当前主视角</span>
          ) : isGenericReciprocalRelation ? (
            <span className="tree-node-relation-line">家族成员</span>
          ) : (
            <>
              {reverseRelationText && (
                <span className="tree-node-relation-line">
                  我是{selfPronoun}：{reverseRelationText}
                </span>
              )}
              <span className={`tree-node-relation-line${reverseRelationText ? ' tree-node-relation-back' : ''}`}>
                {selfPronoun}是我：{relationText}
              </span>
            </>
          )}
        </div>
      )}

      {/* 配偶左右连接点（双向，支持男左女右与女左男右） */}
      <Handle type="source" position={Position.Right} id="right-source" style={{ opacity: 0 }} />
      <Handle type="target" position={Position.Right} id="right-target" style={{ opacity: 0 }} />
      <Handle type="source" position={Position.Left} id="left-source" style={{ opacity: 0 }} />
      <Handle type="target" position={Position.Left} id="left-target" style={{ opacity: 0 }} />

      <div
        className="tree-node-avatar"
      >
        {canDisplaySrc(person.avatar) ? (
          <img
            src={convertLocalSrc(person.avatar)}
            alt={fullName}
            onError={(e) => {
              e.currentTarget.style.display = 'none';
              const parent = e.currentTarget.parentElement;
              if (parent && !parent.querySelector('.avatar-fallback-text')) {
                const span = document.createElement('span');
                span.className = 'avatar-fallback-text';
                span.textContent = person.surname || fullName.slice(0, 1);
                parent.appendChild(span);
              }
            }}
          />
        ) : (
          person.surname
        )}
      </div>
      <div className="tree-node-name">{fullName}</div>
      <div className="tree-node-lifespan">{subtitle}</div>

      {showCoordinates && (
        isEditing ? (
          <div
            className="tree-node-coordinate-input-container"
            onClick={(e) => e.stopPropagation()}
            onMouseDown={(e) => e.stopPropagation()}
          >
            <input
              type="number"
              className="coordinate-input"
              value={editX}
              onChange={(e) => setEditX(e.target.value)}
              onKeyDown={handleKeyDown}
              placeholder="X"
              autoFocus
            />
            <span className="coordinate-comma">,</span>
            <input
              type="number"
              className="coordinate-input"
              value={editY}
              onChange={(e) => setEditY(e.target.value)}
              onKeyDown={handleKeyDown}
              placeholder="Y"
            />
            <button className="btn-coordinate-ok" onClick={handleSave}>✓</button>
            <button className="btn-coordinate-cancel" onClick={handleCancel}>✗</button>
          </div>
        ) : (
          <div
            className="tree-node-coordinate clickable"
            onClick={(e) => {
              e.stopPropagation();
              setEditX(Math.round(posX).toString());
              setEditY(Math.round(posY).toString());
              setIsEditing(true);
            }}
            title="点击手动输入绝对坐标"
          >
            ({Math.round(posX)}, {Math.round(posY)})
          </div>
        )
      )}

      <Handle type="source" position={Position.Bottom} id="bottom" style={{ opacity: 0 }} />

    </div>
  );
}

